#!/usr/bin/env node
/** Exact historical aliases only; unknown URLs continue to return 404. */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import matter from 'gray-matter';
import { createRouteIndex, staticPageUrls } from './check-content-links.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const COLLECTIONS = ['tools', 'comparisons', 'workflows', 'learn', 'stacks'];
const walk = directory => readdirSync(directory, { withFileTypes: true }).flatMap(entry => entry.isDirectory()
  ? walk(join(directory, entry.name)) : [join(directory, entry.name)]);

export function repositoryRoutes(root = ROOT) {
  const locales = JSON.parse(readFileSync(join(root, 'content/locales.json'), 'utf8')).locales.map(l => l.code);
  const verticals = JSON.parse(readFileSync(join(root, 'content/verticals.json'), 'utf8')).verticals.map(v => v.slug);
  const documents = COLLECTIONS.flatMap(collection => walk(join(root, 'content', collection)))
    .filter(file => file.endsWith('.mdx')).map(file => ({ file: relative(root, file), data: matter(readFileSync(file, 'utf8')).data }));
  const pages = join(root, 'apps/web/src/pages');
  const staticPaths = walk(pages).filter(file => file.endsWith('.astro')).flatMap(file => staticPageUrls(relative(pages, file), locales));
  const index = createRouteIndex(documents, locales, verticals, staticPaths);
  if (index.problems.length) throw new Error('Cannot validate redirects against an invalid content route index');
  return index.routes;
}

export function redirectRules(aliases, routes) {
  if (!aliases || typeof aliases !== 'object' || Array.isArray(aliases)) throw new Error('Aliases must be an object');
  const rules = [{ source: '/', destination: '/en/', status: 302 }];
  const sources = new Set(['/']);
  const exactPath = /^\/[A-Za-z0-9./_-]+$/;
  for (const [source, destination] of Object.entries(aliases).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
    if (!exactPath.test(source) || source.endsWith('/') || source.includes('//') || source.split('/').includes('..')) {
      throw new Error('Alias must be an exact path without trailing slash: ' + source);
    }
    if (typeof destination !== 'string' || !exactPath.test(destination) || !destination.endsWith('/') || !routes.has(destination)) {
      throw new Error('Redirect destination must be an existing canonical page: ' + destination);
    }
    if (routes.has(source + '/')) throw new Error('Cannot redirect an existing page: ' + source);
    for (const path of [source, source + '/']) {
      if (sources.has(path)) throw new Error('Duplicate redirect source: ' + path);
      sources.add(path);
      rules.push({ source: path, destination, status: 301 });
    }
  }
  if (rules.length > 2000) throw new Error('Cloudflare Pages permits at most 2000 static redirect rules');
  for (const rule of rules) {
    if (rule.source === rule.destination || sources.has(rule.destination)) throw new Error('Redirect loop or chain: ' + rule.source);
  }
  return rules;
}

export function renderRedirects(rules) {
  return '# Generated by node scripts/legacy-redirects.mjs --write\n'
    + '# Edit scripts/legacy-redirects.json; CI checks targets and this generated file.\n'
    + '# Root language selection remains temporary. Known legacy aliases are permanent.\n'
    + rules.map(rule => rule.source + ' ' + rule.destination + ' ' + rule.status).join('\n') + '\n';
}

export function checkRedirects(root = ROOT, write = false) {
  const aliases = JSON.parse(readFileSync(join(root, 'scripts/legacy-redirects.json'), 'utf8'));
  const rules = redirectRules(aliases, repositoryRoutes(root));
  const expected = renderRedirects(rules);
  const target = join(root, 'apps/web/public/_redirects');
  if (write) writeFileSync(target, expected);
  else if (readFileSync(target, 'utf8') !== expected) throw new Error('Stale _redirects: run node scripts/legacy-redirects.mjs --write');
  return { aliases: Object.keys(aliases).length, rules: rules.length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = checkRedirects(ROOT, process.argv.includes('--write'));
    console.log('[legacy-redirects] ' + result.aliases + ' exact aliases, ' + result.rules + ' validated static rules');
  } catch (error) {
    console.error('[legacy-redirects] ' + error.message);
    process.exitCode = 1;
  }
}
